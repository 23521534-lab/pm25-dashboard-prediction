import pandas as pd
from statsmodels.tsa.stattools import adfuller

df = pd.read_csv("city_day.csv")
df = df[['Date', 'PM2.5']]

df['Date'] = pd.to_datetime(df['Date'])
df = df.sort_values(by='Date')
df.set_index('Date', inplace=True)

df = df.resample('D').mean()
df['PM2.5'] = df['PM2.5'].interpolate(method='linear')

print("ADF:", adfuller(df['PM2.5'])[1])

train = df['PM2.5'][:'2019']
test = df['PM2.5']['2020':]

from statsmodels.tsa.statespace.sarimax import SARIMAX
import warnings

warnings.filterwarnings("ignore")

best_aic = float("inf")
best_order = None
best_seasonal = None

for p in range(2):
    for q in range(2):
        for P in range(2):
            for Q in range(2):
                try:
                    model = SARIMAX(
                        train,
                        order=(p,0,q),
                        seasonal_order=(P,0,Q,7)   # s = 7 (chu kỳ tuần)
                    )
                    result = model.fit(disp=False)

                    if result.aic < best_aic:
                        best_aic = result.aic
                        best_order = (p,0,q)
                        best_seasonal = (P,0,Q,7)

                    print(f"SARIMA{(p,0,q)}x{(P,0,Q,7)} - AIC:{result.aic}")

                except:
                    continue

print("\nBest order:", best_order)
print("Best seasonal:", best_seasonal)
print("Best AIC:", best_aic)

model = SARIMAX(
    train,
    order=best_order,
    seasonal_order=best_seasonal
)

model_fit = model.fit(disp=False)

print(model_fit.summary())

forecast = model_fit.forecast(steps=len(test))

from sklearn.metrics import mean_squared_error, mean_absolute_error
import numpy as np

rmse = np.sqrt(mean_squared_error(test, forecast))
mae = mean_absolute_error(test, forecast)

mape = np.mean(np.abs((test - forecast) / test)) * 100

print("RMSE:", rmse)
print("MAE:", mae)
print("MAPE:", mape)

result_df = pd.DataFrame({
    'Actual': test,
    'Forecast': forecast
})

print(result_df)

