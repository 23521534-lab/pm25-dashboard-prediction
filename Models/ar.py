import pandas as pd
from statsmodels.tsa.stattools import adfuller

df = pd.read_csv("city_day_cleaned.csv")  # dùng file đã clean

df = df[['Date', 'PM2.5']]
df['Date'] = pd.to_datetime(df['Date'])

# group theo ngày (vì có nhiều dòng cùng ngày)
df = df.groupby('Date').mean()

# đảm bảo index là datetime và có thứ tự
df = df.sort_index()

# resample lại cho chắc (fill missing ngày nếu có)
df = df.resample('D').mean()

# nội suy giá trị thiếu
df['PM2.5'] = df['PM2.5'].interpolate(method='linear')

# kiểm tra stationarity
print("ADF p-value:", adfuller(df['PM2.5'])[1])

train_size = int(len(df) * 0.8)

train = df['PM2.5'][:train_size]
test = df['PM2.5'][train_size:]

from statsmodels.tsa.ar_model import AutoReg

model2 = AutoReg(train, lags=2).fit()
model3 = AutoReg(train, lags=3).fit()

print("AIC p=2:", model2.aic)
print("AIC p=3:", model3.aic)

p = 3  # ví dụ chọn 3

model = AutoReg(train, lags=p)
model_fit = model.fit()

print(model_fit.summary())

pred = model_fit.predict(
    start=len(train),
    end=len(train) + len(test) - 1,
    dynamic=False
)

from sklearn.metrics import mean_squared_error, mean_absolute_error
import numpy as np

rmse = np.sqrt(mean_squared_error(test, pred))
mae = mean_absolute_error(test, pred)
mape = np.mean(np.abs((test - pred) / test)) * 100

print("RMSE:", rmse)
print("MAE:", mae)
print("MAPE:", mape)

result = pd.DataFrame({
    'Actual': test,
    'Predicted': pred
})

print(result.head(20))

