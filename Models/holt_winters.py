"""##Mô hình 1: Holt-Winters (Triple Exponential Smoothing)"""

# Train: 75% (~41 tháng), Test: 25% (~14 tháng) — bám theo bài báo gốc
N          = len(monthly)
train_size = int(N * 0.75)

train_data = monthly.iloc[:train_size]
test_data  = monthly.iloc[train_size:]

print(f" Chia dữ liệu:")
print(f"   Train: {len(train_data)} tháng  ({train_data.index[0].strftime('%Y-%m')} → {train_data.index[-1].strftime('%Y-%m')})")
print(f"   Test : {len(test_data)}  tháng  ({test_data.index[0].strftime('%Y-%m')} → {test_data.index[-1].strftime('%Y-%m')})")
print(f"   Test mean: {test_data.mean():.2f} µg/m³  (để tham chiếu với RMSE)")

def rmse(actual, predicted):
    return np.sqrt(mean_squared_error(actual, predicted))

def mae(actual, predicted):
    return mean_absolute_error(actual, predicted)

def mape(actual, predicted):
    actual, predicted = np.array(actual), np.array(predicted)
    mask = actual != 0
    return np.mean(np.abs((actual[mask] - predicted[mask]) / actual[mask])) * 100

def print_metrics(name, actual, predicted):
    r = rmse(actual, predicted)
    m = mae(actual, predicted)
    mp = mape(actual, predicted)
    print(f"\n{'='*50}")
    print(f"  📊 {name}")
    print(f"{'='*50}")
    print(f"  RMSE : {r:.4f}")
    print(f"  MAE  : {m:.4f}")
    print(f"  MAPE : {mp:.4f}%")
    return r, m, mp

