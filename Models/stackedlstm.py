import pandas as pd
import numpy as np

from sklearn.experimental import enable_iterative_imputer
from sklearn.impute import IterativeImputer
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout

# 1. LOAD + CLEAN
df = pd.read_csv("city_day_cleaned.csv")

df['Date'] = pd.to_datetime(df['Date'])

cols = ['PM2.5','PM10','NOx','NO2','NH3']

df = df.groupby('Date')[cols].mean().reset_index()

df = df.sort_values(by='Date')
df.set_index('Date', inplace=True)

# 2. SPLIT
train = df[:'2019']
test = df['2020':]

# 3. IMPUTE (NO LEAK)
imputer = IterativeImputer(random_state=0)

train = pd.DataFrame(imputer.fit_transform(train),
                     columns=cols, index=train.index)

test = pd.DataFrame(imputer.transform(test),
                    columns=cols, index=test.index)

df = pd.concat([train, test])

# 4. FEATURE ENGINEERING
df['PM2.5_lag1'] = df['PM2.5'].shift(1)
df['PM2.5_lag7'] = df['PM2.5'].shift(7)
df['PM2.5_roll7'] = df['PM2.5'].shift(1).rolling(7).mean()

# seasonality
df['month'] = df.index.month
df['month_sin'] = np.sin(2*np.pi*df['month']/12)
df['month_cos'] = np.cos(2*np.pi*df['month']/12)

df.dropna(inplace=True)

# 5. SCALE (NO LEAK)
scaler = MinMaxScaler()

train_scaled = scaler.fit_transform(df.loc[:'2019'])
test_scaled = scaler.transform(df.loc['2020':])

df_scaled = pd.concat([
    pd.DataFrame(train_scaled, columns=df.columns, index=df.loc[:'2019'].index),
    pd.DataFrame(test_scaled, columns=df.columns, index=df.loc['2020':].index)
])

# 6. CREATE SEQUENCE
def create_sequences(data, target_col, window=30):
    X, y, dates = [], [], []
    target_idx = data.columns.get_loc(target_col)

    for i in range(window, len(data)):
        X.append(data.iloc[i-window:i].values)
        y.append(data.iloc[i, target_idx])
        dates.append(data.index[i])

    return np.array(X), np.array(y), np.array(dates)

WINDOW = 30

train_data = df_scaled.loc[:'2019']
test_data = df_scaled.loc['2020':]

X_train, y_train, train_dates = create_sequences(train_data, 'PM2.5', WINDOW)
X_test, y_test, test_dates = create_sequences(test_data, 'PM2.5', WINDOW)

# 7. BUILD STACKED LSTM
model = Sequential()

model.add(LSTM(64, return_sequences=True, input_shape=(X_train.shape[1], X_train.shape[2])))
model.add(Dropout(0.2))

model.add(LSTM(32, return_sequences=False))
model.add(Dropout(0.2))

model.add(Dense(1))

model.compile(optimizer='adam', loss='mse')

# 8. TRAIN
history = model.fit(
    X_train, y_train,
    epochs=20,
    batch_size=32,
    validation_split=0.1,
    verbose=1
)

# 9. PREDICT
y_pred = model.predict(X_test)

# 10. INVERSE SCALE
def inverse_transform(y_scaled, df_ref, scaler, target_col):
    temp = np.zeros((len(y_scaled), df_ref.shape[1]))
    target_idx = df_ref.columns.get_loc(target_col)

    temp[:, target_idx] = y_scaled.flatten()
    return scaler.inverse_transform(temp)[:, target_idx]

y_test_inv = inverse_transform(y_test, df, scaler, 'PM2.5')
y_pred_inv = inverse_transform(y_pred, df, scaler, 'PM2.5')

# 11. EVALUATE
rmse = np.sqrt(mean_squared_error(y_test_inv, y_pred_inv))
mae = mean_absolute_error(y_test_inv, y_pred_inv)
mape = np.mean(np.abs((y_test_inv - y_pred_inv) / y_test_inv)) * 100

print("RMSE:", rmse)
print("MAE:", mae)
print("MAPE:", mape)

# 12. SHOW RESULT
result = pd.DataFrame({
    'Date': test_dates,
    'Actual': y_test_inv,
    'Predicted': y_pred_inv
})

result.set_index('Date', inplace=True)

print(result)

