import pandas as pd
import numpy as np

from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense

# 1. LOAD + FIX CLEAN DATA
df = pd.read_csv("city_day_cleaned.csv")

df['Date'] = pd.to_datetime(df['Date'])

base_features = ['PM2.5','PM10','NOx','NO2','NH3']
df = df[['Date'] + base_features]

df = df.groupby('Date').mean().reset_index()

df = df.sort_values(by='Date').reset_index(drop=True)

# 2. FEATURE ENGINEERING

# LOG (giữ nguyên)
df['PM2.5'] = np.log1p(df['PM2.5'])

# lag + rolling
df['PM2.5_lag1'] = df['PM2.5'].shift(1)
df['PM2.5_lag7'] = df['PM2.5'].shift(7)
df['PM2.5_roll7'] = df['PM2.5'].shift(1).rolling(7).mean()

# diff
df['PM2.5_diff1'] = df['PM2.5'].diff()

# time features
df['month'] = df['Date'].dt.month
df['month_sin'] = np.sin(2*np.pi*df['month']/12)
df['month_cos'] = np.cos(2*np.pi*df['month']/12)

# missing
df.fillna(method='ffill', inplace=True)
df.dropna(inplace=True)

# 3. FEATURE / TARGET
features = [
    'PM2.5',
    'PM2.5_lag1',
    'PM2.5_lag7',
    'PM2.5_roll7',
    'PM2.5_diff1',
    'month_sin',
    'month_cos'
]

target = 'PM2.5'

X = df[features].values
y = df[[target]].values

# 4. SPLIT
train_size = int(len(X) * 0.8)

X_train_raw, X_test_raw = X[:train_size], X[train_size:]
y_train_raw, y_test_raw = y[:train_size], y[train_size:]

# 5. SCALE (NO LEAK)
scaler_X = MinMaxScaler()
scaler_y = MinMaxScaler()

X_train = scaler_X.fit_transform(X_train_raw)
X_test = scaler_X.transform(X_test_raw)

y_train = scaler_y.fit_transform(y_train_raw)
y_test = scaler_y.transform(y_test_raw)

# 6. CREATE SEQUENCE + DATE
def create_sequences(X, y, dates, time_steps=30):
    Xs, ys, ds = [], [], []

    for i in range(len(X) - time_steps):
        Xs.append(X[i:i+time_steps])
        ys.append(y[i+time_steps])
        ds.append(dates[i+time_steps])

    return np.array(Xs), np.array(ys), np.array(ds)

time_steps = 30

dates = df['Date'].values

X_seq_train, y_seq_train, _ = create_sequences(
    X_train, y_train, dates[:train_size], time_steps
)

X_seq_test, y_seq_test, test_dates = create_sequences(
    X_test, y_test, dates[train_size:], time_steps
)

# 7. MODEL (Vanilla LSTM)
model = Sequential()
model.add(LSTM(64, input_shape=(X_seq_train.shape[1], X_seq_train.shape[2])))
model.add(Dense(32, activation='relu'))
model.add(Dense(1))

model.compile(optimizer='adam', loss='mse')

model.summary()

# 8. TRAIN
history = model.fit(
    X_seq_train, y_seq_train,
    epochs=20,
    batch_size=32,
    validation_data=(X_seq_test, y_seq_test),
    shuffle=False,
    verbose=1
)

# 9. PREDICT
y_pred = model.predict(X_seq_test)

# 10. INVERSE SCALE
y_test_inv = scaler_y.inverse_transform(y_seq_test)
y_pred_inv = scaler_y.inverse_transform(y_pred)

y_test_final = np.expm1(y_test_inv)
y_pred_final = np.expm1(y_pred_inv)

# 11. EVALUATE
rmse = np.sqrt(mean_squared_error(y_test_final, y_pred_final))
mae = mean_absolute_error(y_test_final, y_pred_final)
mape = np.mean(np.abs((y_test_final - y_pred_final) / y_test_final)) * 100

print("RMSE:", rmse)
print("MAE:", mae)
print("MAPE:", mape)

# 12. SHOW RESULT
result = pd.DataFrame({
    'Date': test_dates,
    'Actual': y_test_final.flatten(),
    'Predicted': y_pred_final.flatten()
})

result.set_index('Date', inplace=True)

print(result)

