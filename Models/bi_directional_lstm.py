import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout, Bidirectional
from tensorflow.keras.callbacks import EarlyStopping
import tensorflow as tf

print("\n" + "="*60)
print("  MÔ HÌNH BI-DIRECTIONAL LSTM (MULTIVARIATE)")
print("="*60)

# 1. LOAD DATA CLEAN
df = pd.read_csv("city_day_cleaned.csv")

df['Date'] = pd.to_datetime(df['Date'])
df = df.sort_values('Date')

df = df.groupby('Date').mean().reset_index()

features = ['PM2.5','PM10','NOx','NO2','NH3']

data = df[['Date'] + features].dropna().copy()
data.set_index('Date', inplace=True)

# 2. TRAIN TEST SPLIT
train_size = int(len(data) * 0.8)

train_data = data.iloc[:train_size]
test_data  = data.iloc[train_size:]

# 3. SCALE
scaler = MinMaxScaler()
scaler.fit(train_data)

scaled_train = scaler.transform(train_data)
scaled_test  = scaler.transform(test_data)

# 4. CREATE SEQUENCES
LOOK_BACK = 30

def create_sequences(dataset, look_back=30):
    X, y = [], []
    for i in range(len(dataset) - look_back):
        X.append(dataset[i:i+look_back])
        y.append(dataset[i+look_back][:2])  # PM2.5, PM10
    return np.array(X), np.array(y)

X_train, y_train = create_sequences(scaled_train, LOOK_BACK)
X_test,  y_test  = create_sequences(scaled_test,  LOOK_BACK)

print(f"X_train: {X_train.shape} | y_train: {y_train.shape}")
print(f"X_test:  {X_test.shape}  | y_test:  {y_test.shape}")

# 5. BUILD MODEL
def build_bilstm(look_back, n_features):
    model = Sequential([
        Bidirectional(
            LSTM(128, return_sequences=True, dropout=0.2),
            input_shape=(look_back, n_features)
        ),
        Bidirectional(
            LSTM(128, return_sequences=True, dropout=0.2)
        ),
        LSTM(64, dropout=0.2),
        Dense(32, activation='relu'),
        Dense(2)   # PM2.5 & PM10
    ])

    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
        loss='mse'
    )
    return model

model = build_bilstm(LOOK_BACK, X_train.shape[2])
model.summary()

# 6. TRAIN
early_stop = EarlyStopping(
    monitor='val_loss',
    patience=10,
    restore_best_weights=True
)

history = model.fit(
    X_train, y_train,
    validation_data=(X_test, y_test),
    epochs=30,
    batch_size=32,
    callbacks=[early_stop],
    shuffle=False
)

# 7. PREDICT
y_pred = model.predict(X_test)

# 8. INVERSE SCALE
def inverse_transform(y_scaled, scaler, feature_index):
    temp = np.zeros((len(y_scaled), scaler.n_features_in_))
    temp[:, feature_index] = y_scaled
    return scaler.inverse_transform(temp)[:, feature_index]

# PM2.5
y_test_pm25 = inverse_transform(y_test[:,0], scaler, 0)
y_pred_pm25 = inverse_transform(y_pred[:,0], scaler, 0)

# PM10
y_test_pm10 = inverse_transform(y_test[:,1], scaler, 1)
y_pred_pm10 = inverse_transform(y_pred[:,1], scaler, 1)

# 9. DATE ALIGN
test_dates = data.index[train_size + LOOK_BACK:]

# 10. EVALUATE
def evaluate(y_true, y_pred, name):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    r2 = r2_score(y_true, y_pred)
    mape = np.mean(np.abs((y_true - y_pred)/(y_true+1e-8))) * 100

    print(f"\n{name}")
    print("MAE:", mae)
    print("RMSE:", rmse)
    print("R2:", r2)
    print("MAPE:", mape)

evaluate(y_test_pm25, y_pred_pm25, "PM2.5")
evaluate(y_test_pm10, y_pred_pm10, "PM10")

# 11. IN BẢNG KẾT QUẢ
result_df = pd.DataFrame({
    'Date': test_dates,
    'Actual_PM2.5': y_test_pm25,
    'Predicted_PM2.5': y_pred_pm25,
    'Actual_PM10': y_test_pm10,
    'Predicted_PM10': y_pred_pm10
})

print(result_df.head(20))

# 12. PLOT
plt.figure(figsize=(14,6))

plt.subplot(1,2,1)
plt.plot(test_dates, y_test_pm25, label='Actual')
plt.plot(test_dates, y_pred_pm25, label='Predicted')
plt.title("PM2.5 Prediction")
plt.legend()

plt.subplot(1,2,2)
plt.plot(test_dates, y_test_pm10, label='Actual')
plt.plot(test_dates, y_pred_pm10, label='Predicted')
plt.title("PM10 Prediction")
plt.legend()

plt.tight_layout()
plt.show()

