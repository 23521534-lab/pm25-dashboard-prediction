import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from prophet import Prophet
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

df = pd.read_csv("city_day.csv")
df['Date'] = pd.to_datetime(df['Date'])

city = 'Delhi'
df_city = df[df['City'] == city].copy()
df_city = df_city.sort_values('Date')

df_model = df_city[['Date','PM2.5','PM10']].copy()

# Nội suy missing
df_model['PM2.5'] = df_model['PM2.5'].interpolate()
df_model['PM10'] = df_model['PM10'].interpolate()

def train_prophet(df, target_name):
    df_tmp = df[['Date', target_name]].copy()

    # rename cho Prophet
    df_tmp = df_tmp.rename(columns={
        'Date': 'ds',
        target_name: 'y'
    })

    # log transform
    df_tmp['y'] = np.log1p(df_tmp['y'])

    # split
    train_size = int(len(df_tmp) * 0.8)
    train = df_tmp[:train_size]
    test = df_tmp[train_size:]

    # model
    model = Prophet(
        yearly_seasonality=True,
        weekly_seasonality=True,
        daily_seasonality=False
    )

    model.fit(train)

    # forecast
    future = model.make_future_dataframe(periods=len(test))
    forecast = model.predict(future)

    # lấy test
    y_pred_log = forecast['yhat'][-len(test):].values
    y_true_log = test['y'].values

    # inverse log
    y_pred = np.expm1(y_pred_log)
    y_true = np.expm1(y_true_log)

    return model, forecast, test, y_true, y_pred

df_model = df_city[['Date','PM2.5','PM10']].copy()

df_model['PM2.5'] = df_model['PM2.5'].interpolate()
df_model['PM10'] = df_model['PM10'].interpolate()

model_25, forecast_25, test_25, y_true_25, y_pred_25 = train_prophet(df_model, 'PM2.5')
model_10, forecast_10, test_10, y_true_10, y_pred_10 = train_prophet(df_model, 'PM10')

def mape(y_true, y_pred):
    y_true, y_pred = np.array(y_true), np.array(y_pred)
    return np.mean(np.abs((y_true - y_pred) / (y_true + 1e-8))) * 100
def evaluate(y_true, y_pred, name):
    mae = mean_absolute_error(y_true, y_pred)
    mse = mean_squared_error(y_true, y_pred)
    rmse = np.sqrt(mse)
    rse = np.sum((y_true - y_pred)**2) / np.sum((y_true - np.mean(y_true))**2)
    r2 = r2_score(y_true, y_pred)
    mape_value = mape(y_true, y_pred)

    print(f"\n===== {name} =====")
    print(f"MAE  : {mae:.4f}")
    print(f"MSE  : {mse:.4f}")
    print(f"RMSE : {rmse:.4f}")
    print(f"RSE  : {rse:.4f}")
    print(f"R2   : {r2:.4f}")
    print(f"MAPE  : {mape_value:.2f}%")

evaluate(y_true_25, y_pred_25, "PM2.5 (baseline)")
evaluate(y_true_10, y_pred_10, "PM10 (baseline)")

plt.figure(figsize=(12,5))
plt.plot(test_25['ds'], y_true_25, label='Actual PM2.5')
plt.plot(test_25['ds'], y_pred_25, label='Predicted PM2.5')
plt.legend()
plt.title("PM2.5 Baseline")
plt.show()

plt.figure(figsize=(12,5))
plt.plot(test_10['ds'], y_true_10, label='Actual PM10')
plt.plot(test_10['ds'], y_pred_10, label='Predicted PM10')
plt.legend()
plt.title("PM10 Baseline")
plt.show()