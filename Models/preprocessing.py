from pyspark.sql import SparkSession
from pyspark.sql.functions import *
from pyspark.sql.window import Window
from pyspark.ml.feature import VectorAssembler
from pyspark.ml.regression import LinearRegression

# 1. INIT SPARK
spark = SparkSession.builder \
    .appName("AirQualityCleaning") \
    .getOrCreate()

# 2. LOAD DATA
df = spark.read.csv(
    "city_day.csv",
    header=True,
    inferSchema=True
)

df = df.withColumn("Date", to_date("Date", "yyyy-MM-dd"))

window_spec = Window.partitionBy("City").orderBy("Date")

# 3. IMPUTE PM10 USING PM2.5
train_df = df.filter(
    col("PM2.5").isNotNull() &
    col("PM10").isNotNull()
)

assembler = VectorAssembler(
    inputCols=["PM2.5"],
    outputCol="features"
)

train_data = assembler.transform(train_df)

lr = LinearRegression(
    featuresCol="features",
    labelCol="PM10"
)

model = lr.fit(train_data)

predict_df = df.filter(
    col("PM10").isNull() &
    col("PM2.5").isNotNull()
)

pred_data = assembler.transform(predict_df)

predictions = model.transform(pred_data).select(
    "City",
    "Date",
    col("prediction").alias("PM10_pred")
)

df = df.join(
    predictions,
    ["City", "Date"],
    "left"
).withColumn(
    "PM10",
    coalesce(col("PM10"), col("PM10_pred"))
).drop("PM10_pred")

# 4. MEAN BEFORE-AFTER
cols = ["PM2.5", "PM10", "NOx", "NO2", "NH3"]

for c in cols:
    if c in df.columns:
        df = df.withColumn(
            "prev",
            lag(c).over(window_spec)
        ).withColumn(
            "next",
            lead(c).over(window_spec)
        )

        df = df.withColumn(
            c,
            when(
                col(c).isNull() &
                col("prev").isNotNull() &
                col("next").isNotNull(),
                (col("prev") + col("next")) / 2
            ).otherwise(col(c))
        ).drop("prev", "next")

# 5. FORWARD FILL
for c in cols:
    if c in df.columns:
        df = df.withColumn(
            c,
            last(c, ignorenulls=True).over(window_spec)
        )

# 6. BACKWARD FILL
reverse_window = Window.partitionBy("City").orderBy(desc("Date"))

for c in cols:
    if c in df.columns:
        df = df.withColumn(
            c,
            last(c, ignorenulls=True).over(reverse_window)
        )

# 7. KEEP COLUMNS
cols_keep = [
    "City",
    "Date",
    "PM2.5",
    "PM10",
    "NOx",
    "NO2",
    "NH3"
]

df_clean = df.select(*cols_keep)

# 8. SAVE CLEAN DATA
df_clean.write \
    .mode("overwrite") \
    .option("header", True) \
    .csv("city_day_cleaned")