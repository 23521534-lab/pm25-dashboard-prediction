import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv1D, MaxPooling1D, LSTM, Dense, Dropout
from tensorflow.keras.callbacks import EarlyStopping

df = pd.read_csv("city_day.csv")
df['Date'] = pd.to_datetime(df['Date'])

city = 'Delhi'
df_city = df[df['City'] == city].copy()
df_city = df_city.sort_values('Date')

# chọn feature
features = ['PM2.5', 'PM10', 'NO2', 'CO', 'O3', 'SO2']
data = df_city[['Date'] + features].dropna()
data.set_index('Date', inplace=True)

"""CHUẨN HÓA DỮ LIỆU"""

train_size_raw = int(len(data) * 0.8)

train_data = data.iloc[:train_size_raw]
test_data = data.iloc[train_size_raw:]
scaler = MinMaxScaler()
scaler.fit(train_data)

scaled_train = scaler.transform(train_data)
scaled_test = scaler.transform(test_data)

"""TẠO DATASET"""

def create_dataset(dataset, time_step=30):
    X, y = [], []
    for i in range(len(dataset) - time_step):
        X.append(dataset[i:i+time_step])
        y.append(dataset[i+time_step][:2])
    return np.array(X), np.array(y)

time_step = 30

X_train, y_train = create_dataset(scaled_train, time_step)
X_test, y_test = create_dataset(scaled_test, time_step)

""" XÂY DỰNG MÔ HÌNH CNN-LSTM"""

model = Sequential()

# CNN
model.add(Conv1D(
    filters=64,
    kernel_size=3,
    activation='relu',
    input_shape=(time_step, X_train.shape[2])
))
model.add(MaxPooling1D(pool_size=2))
model.add(Dropout(0.2))

# LSTM
model.add(LSTM(
    units=64,
    return_sequences=False
))
model.add(Dropout(0.2))

#  Dense
model.add(Dense(32, activation='relu'))
model.add(Dense(2))   # 2 output: PM2.5 và PM10

# Compile
model.compile(
    optimizer='adam',
    loss='mse'
)

model.summary()

""" TRAIN"""

early_stop = EarlyStopping(
    monitor='val_loss',
    patience=5,
    restore_best_weights=True
)

history = model.fit(
    X_train, y_train,
    validation_data=(X_test, y_test),
    epochs=30,
    batch_size=32,
    callbacks=[early_stop]
)

y_pred = model.predict(X_test)

def inverse_transform(y_scaled, scaler, feature_index):
    temp = np.zeros((len(y_scaled), scaler.n_features_in_))
    temp[:, feature_index] = y_scaled
    return scaler.inverse_transform(temp)[:, feature_index]

# PM2.5
y_test_pm25 = inverse_transform(y_test[:, 0], scaler, 0)
y_pred_pm25 = inverse_transform(y_pred[:, 0], scaler, 0)

# PM10
y_test_pm10 = inverse_transform(y_test[:, 1], scaler, 1)
y_pred_pm10 = inverse_transform(y_pred[:, 1], scaler, 1)

def evaluate(y_true, y_pred, name):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    r2 = r2_score(y_true, y_pred)

    # tránh chia cho 0
    mape = np.mean(np.abs((y_true - y_pred) / (y_true + 1e-8))) * 100

    print(f"\n{name}")
    print("MAE:", mae)
    print("RMSE:", rmse)
    print("R2:", r2)
    print("MAPE:", mape)

evaluate(y_test_pm25, y_pred_pm25, "PM2.5")
evaluate(y_test_pm10, y_pred_pm10, "PM10")

plt.figure(figsize=(14,6))

# PM2.5
plt.subplot(1,2,1)
plt.plot(y_test_pm25, label='Actual')
plt.plot(y_pred_pm25, label='Predicted')
plt.title("PM2.5 Prediction")
plt.legend()

# PM10
plt.subplot(1,2,2)
plt.plot(y_test_pm10, label='Actual')
plt.plot(y_pred_pm10, label='Predicted')
plt.title("PM10 Prediction")
plt.legend()

plt.tight_layout()
plt.show()

